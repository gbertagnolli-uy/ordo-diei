import { chromium } from "playwright";
const b = await chromium.launch({ executablePath: "C:/Users/evoxu/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe" });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const base = "http://localhost:3157";
await p.request.post(base + "/api/auth/login", { data: { userId: 3, pinSecreto: "1234" } });
await p.goto(base + "/dashboard/habitos", { waitUntil: "networkidle", timeout: 120000 });
await p.keyboard.press("Escape"); await p.waitForTimeout(800);
const card = p.locator("body");
console.log("tarjeta:", await card.count());
await card.getByRole("button", { name: "Hecho", exact: true }).click(); await p.waitForTimeout(700);
console.log("diálogo:", await p.getByText("¿Qué leíste hoy?").isVisible());
const ta = p.getByPlaceholder("Hoy leí sobre...");
await ta.fill("a".repeat(79));
const enviar = p.getByRole("dialog").getByRole("button").filter({ hasNotText: /Cancelar|Close|Cerrar/ }).last();
console.log("79 → botón", (await enviar.innerText()).trim(), "deshabilitado:", await enviar.isDisabled());
await ta.fill("Hoy leí sobre San Francisco: dejó todo para seguir a Jesús y cuidar a los pobres con alegría.");
console.log("80+ → deshabilitado:", await enviar.isDisabled());
await p.screenshot({ path: process.argv[2] });
await enviar.click(); await p.waitForTimeout(1500);
console.log("marcado hecho:", await card.getByText(/Hecho hoy/).count());
await b.close();
